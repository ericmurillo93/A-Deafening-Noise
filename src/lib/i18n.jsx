const I18nContext = createContext({ language: "en", setLanguage: () => {}, t: (key) => key, locale: "en-GB" });

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(STORAGE_KEY) === "es" ? "es" : "en");
  const setLanguage = (next) => {
    const language = next === "es" ? "es" : "en";
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    setLanguageState(language);
  };
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    locale: language === "es" ? "es-ES" : "en-GB",
    t: (key, values = {}) => {
      let result = translations[language]?.[key] || key;
      Object.entries(values).forEach(([name, value]) => { result = result.replaceAll(`{${name}}`, String(value)); });
      return result;
    },
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
